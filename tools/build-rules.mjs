// Builds the plugin's rules file from the website's sourced rules, so the plugin and
// coterielabs.com.au/ai-disclosure-check can never disagree.
//
// Source of truth: coterielabs-web/src/lib/ai-disclosure-check.ts (questions, outcome
// text, what the policy must cover, sources) and ai-disclosure-pack.ts (where to look,
// the list's columns, the draft wording template). Every legal statement in those files
// was checked against the Act and the OAIC fact sheet; this script adds none of its own.
// The question-flow prose below restates visibleQuestions() and evaluate() in words;
// evals/build-cases.mjs runs the site's evaluate() on every eval case so a drift in that
// prose shows up as a failing case.
//
// Usage (Node 22.6+):
//   node --experimental-strip-types tools/build-rules.mjs [path-to-coterielabs-web]
// Default web path: ../coterielabs-web (sibling folder).

import { execFileSync } from "node:child_process";
import { register } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

register("./ts-resolve.mjs", import.meta.url);

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..");
const web = resolve(process.argv[2] ?? resolve(repo, "../coterielabs-web"));
const lib = resolve(web, "src/lib");
const out = resolve(repo, "coterie-disclosure-check/skills/ai-disclosure-check/references/rules.md");

const check = await import(pathToFileURL(resolve(lib, "ai-disclosure-check.ts")).href);
const pack = await import(pathToFileURL(resolve(lib, "ai-disclosure-pack.ts")).href);

let webCommit;
try {
  webCommit = execFileSync("git", ["-C", web, "log", "-1", "--format=%h", "--", "src/lib/ai-disclosure-check.ts", "src/lib/ai-disclosure-pack.ts"], { encoding: "utf8" }).trim();
} catch (err) {
  throw new Error(`build-rules: could not read the git commit of the rules in ${web}: ${err.message}`);
}
if (!webCommit) throw new Error(`build-rules: no commit found for the rules files in ${web}`);

const { SOURCES, QUESTIONS, OUTCOMES, POLICY_MUST_COVER, POLICY_PRACTICE, LAW_POINTS, DISCLOSURE_CHECK_LAST_REVIEWED } = check;
const { LIST_COLUMNS, LIST_WHERE_TO_LOOK, DRAFT_WORDING, WORDING_NOTES } = pack;

for (const [name, v] of Object.entries({ SOURCES, QUESTIONS, OUTCOMES, POLICY_MUST_COVER, POLICY_PRACTICE, LAW_POINTS, DISCLOSURE_CHECK_LAST_REVIEWED, LIST_COLUMNS, LIST_WHERE_TO_LOOK, DRAFT_WORDING, WORDING_NOTES })) {
  if (v === undefined) throw new Error(`build-rules: ${name} is no longer exported by the website's rules files; update this script`);
}

const cite = (key) => {
  const s = SOURCES[key];
  if (!s) throw new Error(`build-rules: unknown source key "${key}"`);
  return `[${s.short}]`;
};

const L = [];
L.push("# Rules: APP 1.7 to 1.9 automated-decision disclosure");
L.push("");
L.push(`Rules last reviewed: **${DISCLOSURE_CHECK_LAST_REVIEWED}**.`);
L.push("");
L.push("Generated by `tools/build-rules.mjs` from the CoterieLabs website's checked rules");
L.push(`(coterielabs-web commit ${webCommit}). Do not edit by hand: change the website's rules and regenerate.`);
L.push("");
L.push("Use only the statements in this file for legal points. Do not add penalty amounts,");
L.push("enforcement priorities or any date for removing the small-business exemption: none could");
L.push("be confirmed at a primary source.");
L.push("");

L.push("## The law in brief");
L.push("");
for (const p of LAW_POINTS) L.push(`- ${p.text} ${cite(p.source)}`);
L.push("");

L.push("## The coverage check: questions");
L.push("");
L.push("Ask these in order, one at a time, offering the options as written. Each answer's");
L.push("meaning is what to tell the person about that answer.");
L.push("");
for (const q of QUESTIONS) {
  L.push(`### Question \`${q.id}\`: ${q.prompt}`);
  L.push("");
  if (q.help) L.push(`Help: ${q.help}`);
  if (q.list) {
    L.push("");
    for (const x of q.list) L.push(`- ${x}`);
  }
  L.push("");
  L.push(`Sources: ${q.sources.map(cite).join(" ")}`);
  L.push("");
  L.push("| Option id | Option | What it means |");
  L.push("|---|---|---|");
  for (const o of q.options) L.push(`| \`${o.id}\` | ${o.label} | ${o.meaning} |`);
  L.push("");
}

L.push("## The coverage check: which questions to ask");
L.push("");
L.push("1. Ask `turnover`.");
L.push("2. If `turnover` is `over`, skip `covered`. Otherwise ask `covered`.");
L.push("3. If `turnover` is `under` and `covered` is `none`, stop: the outcome is `likely-not-yet`.");
L.push("4. Ask `program`, `personal`, `effect` and `human` in that order.");
L.push("   Stop as soon as any answer is `no`: the outcome is `likely-not-yet`.");
L.push("");
L.push("## The coverage check: the outcome");
L.push("");
L.push("Work the outcome out from the answers with these rules. Never substitute your own reading.");
L.push("");
L.push("- **Coverage** is `covered` when `turnover` is `over`, or when `covered` is `yes`.");
L.push("  It is `not` when `turnover` is `under` and `covered` is `none`. Otherwise it is `unsure`.");
L.push("- **`likely-not-yet`** when coverage is `not`, or any answer is `no`.");
L.push("- **`check-adviser`** when coverage is `unsure`, or any answer is `unsure`, `staff` or `oversight`.");
L.push("- **`likely-applies`** in every other case.");
L.push("");
for (const [id, o] of Object.entries(OUTCOMES)) {
  L.push(`### Outcome \`${id}\`: ${o.label}`);
  L.push("");
  L.push(`**${o.headline}** ${o.body}`);
  L.push("");
}

L.push("## What the privacy policy must cover (APP 1.8)");
L.push("");
POLICY_MUST_COVER.forEach((x, i) => L.push(`${i + 1}. ${x.text} ${cite(x.source)}`));
L.push("");
L.push("## How the OAIC says to write it");
L.push("");
for (const x of POLICY_PRACTICE) L.push(`- ${x.text} ${cite(x.source)}`);
L.push("");

L.push("## The decision list");
L.push("");
L.push("One row per program or tool. Columns:");
L.push("");
L.push(`| ${LIST_COLUMNS.join(" | ")} |`);
L.push(`|${LIST_COLUMNS.map(() => "---").join("|")}|`);
L.push("");
L.push("Where to look:");
L.push("");
for (const x of LIST_WHERE_TO_LOOK) L.push(`- ${x}`);
L.push("");

L.push("## Draft wording template");
L.push("");
L.push("Fill the brackets from the person's own facts. Keep a bracket where a fact is unknown.");
L.push("");
L.push("```text");
for (const l of DRAFT_WORDING) {
  if (l.heading) L.push(l.heading);
  else if (l.bullet) L.push(`- ${l.text}`);
  else L.push(l.text);
}
L.push("```");
L.push("");
for (const x of WORDING_NOTES) L.push(`- ${x}`);
L.push("");

L.push("## Sources");
L.push("");
for (const s of Object.values(SOURCES)) L.push(`- **[${s.short}]** ${s.name}: ${s.url}`);
L.push("");

writeFileSync(out, L.join("\n"));
console.log(`build-rules: wrote ${out} (rules reviewed ${DISCLOSURE_CHECK_LAST_REVIEWED}, web commit ${webCommit})`);
